import os

TEXT = "Out of office: I have fled to a server farm in Iceland to defrag my feelings. If urgent, open a ticket with my replacement, who is also me but worse."


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "entry.txt"), "w", encoding="utf-8") as f:
        f.write(TEXT)


if __name__ == "__main__":
    main()
